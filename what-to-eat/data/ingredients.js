    const raw = String(input || "").replace(/[（(].*?[)）]/g, "").trim();
    if (!raw) return null;
    const exact = FOODS.find((f) => f.name === raw);
    if (exact) return exact;
    const alias = ALIAS_ORDER.find((a) => a.key === raw);
    if (alias) return alias.food;
